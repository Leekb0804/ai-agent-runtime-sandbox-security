/*
 * detector.h
 *
 * ===== 이 파일의 역할 =====
 * "탐지기"가 무엇이고 어떤 모양이어야 하는지를 정의하는 인터페이스 헤더다.
 * 구현(코드)은 없고 타입 정의만 있다. 디스패처(dispatcher.c)와 모든 탐지기
 * (detectors/ *.c)가 이 헤더를 include 해서 같은 약속을 공유한다.
 * (event.h 가 "커널 <-> 유저" 사이의 약속이라면, 이 파일은 "디스패처 <-> 탐지기" 사이의 약속)
 *
 * ===== 탐지기란 =====
 * 이벤트 하나를 받아 판정(없음 / SUSPECT / BLOCK)을 돌려주는 함수다.
 * 탐지기는 "판단"만 한다. 화면 출력, 로그 기록, 프로세스 종료는 하지 않는다.
 * 그렇게 해야 탐지기가 늘어나도 대응 방식(출력/로그/kill switch)은 한 곳에서
 * 같은 규칙으로 처리된다.
 */

/*
 * include guard.
 * 같은 헤더가 여러 경로로 두 번 include 되면 같은 구조체를 두 번 정의해서
 * 컴파일 에러가 난다. #ifndef ~ #endif 로 "처음 한 번만" 내용을 읽게 막는다.
 */
#ifndef DETECTOR_H
#define DETECTOR_H

#include <stddef.h>               /* size_t 타입 */

/*
 * <linux/types.h> 는 __u32, __u64 같은 고정 크기 정수 타입을 제공한다.
 * 아래 "bpf/event.h" 가 이 타입을 쓰므로 반드시 event.h 보다 먼저 include 해야 한다.
 * (eBPF 쪽에서는 vmlinux.h 가 같은 역할을 하지만, 유저스페이스에서는 이 헤더를 쓴다.
 *  둘을 한 파일에서 섞으면 타입 중복 정의 에러가 난다)
 */
#include <linux/types.h>
#include "bpf/event.h"            /* struct event_hdr, enum evt_kind 등 이벤트 형식 */

/*
 * 판정 수준.
 *   V_BLOCK   : 확실한 위험. 4일차 이후에는 kill switch 로 세션을 종료할 대상.
 *   V_SUSPECT : 정상 작업과 구분이 어려움. 종료하지 않고 기록만 하고,
 *               세션이 끝난 뒤 사람이 리포트로 검토한다 (과잉 차단 방지).
 * 0 을 일부러 비워 둔 이유: 초기화되지 않은(0) 값이 우연히 유효한 판정처럼
 * 보이는 것을 막기 위해서다.
 */
enum verdict_level {
    V_SUSPECT = 1,
    V_BLOCK   = 2,
};

/*
 * 판정 하나. 탐지기가 level 과 reason 을 채우고, detector 는 디스패처가 채운다.
 * (탐지기가 자기 이름을 속여서 다른 탐지기인 척하지 못하게 하려는 의도도 있다)
 */
struct verdict {
    enum verdict_level level;
    const char *detector;         /* 판정을 낸 탐지기 이름. 디스패처가 채움 */
    char reason[128];             /* 사람이 읽을 이유. 탐지기가 snprintf 로 채움 (최대 127자 + NUL) */
};

/*
 * 이벤트 종류 -> 비트 하나로 바꾸는 매크로.
 *
 * 탐지기가 구독할 종류를 "비트마스크"(정수 하나의 각 비트를 스위치처럼 쓰는 방식)로 표현한다.
 *   EVT_EXEC  = 1 -> 1u << 1 = 0b0010
 *   EVT_WRITE = 2 -> 1u << 2 = 0b0100
 * 여러 종류를 구독하려면 | (OR) 로 합친다:  KIND_BIT(EVT_EXEC) | KIND_BIT(EVT_WRITE) = 0b0110
 * 구독 여부 검사는 & (AND):  (d->kinds & KIND_BIT(kind)) 가 0 이 아니면 구독 중.
 *
 * 1u 의 u 는 부호 없는(unsigned) 정수라는 뜻이다. 부호 있는 int 는 비트를 최상위까지
 * 밀면 동작이 정의되지 않으므로 unsigned 를 쓴다. 인자를 괄호로 감싼 (k) 는
 * 매크로 인자에 수식이 들어와도 우선순위가 꼬이지 않게 하는 관례다.
 * kind 가 32 이상이면 32비트를 넘어 정의되지 않은 동작이 되므로, 디스패처가
 * 호출 전에 범위를 검사한다.
 */
#define KIND_BIT(k) (1u << (k))

/*
 * 탐지기 한 개의 정의.
 *
 * on_event 는 "함수 포인터"다. 함수의 주소를 담는 변수라서, 탐지기마다 다른 함수를
 * 넣어 두면 디스패처가 탐지기의 종류를 몰라도 d->on_event(...) 로 호출할 수 있다.
 * (다른 언어의 인터페이스/콜백과 같은 역할)
 *
 * on_event 의 반환값 약속:
 *    1  : 판정이 있다. out 을 채웠으니 디스패처가 읽어 가라.
 *    0  : 판정 없음 (정상으로 보임).
 *   <0  : 탐지기 내부 오류. 디스패처가 세어 두었다가 연속으로 반복되면 그 탐지기를 끈다.
 *
 * 인자:
 *   h   : 이벤트 시작 주소. ring buffer 메모리를 "직접" 가리키므로, 함수가 끝나면
 *         그 자리는 다른 이벤트로 덮어쓰여진다. 나중에도 필요한 값은 함수 안에서
 *         복사해 두어야 한다 (이 약속은 상관 탐지기를 만드는 2주차에 중요해진다).
 *   len : 이벤트 전체 바이트 수. h 를 evt_exec 등으로 캐스팅하기 전에 확인할 것.
 *   out : 판정을 채울 곳. 디스패처가 0 으로 초기화해서 넘겨준다.
 */
struct detector {
    const char *name;             /* 탐지기 이름 (판정과 로그에 표시됨) */
    __u32 kinds;                  /* 구독할 이벤트 종류의 비트마스크 */
    int (*on_event)(const struct event_hdr *h, size_t len, struct verdict *out);

    /*
     * 아래 두 필드는 디스패처가 관리하는 런타임 상태다. 탐지기 파일에서는 값을 적지 않는다.
     * (static 변수로 선언한 구조체는 지정하지 않은 필드가 자동으로 0 이 된다)
     */
    unsigned err_streak;          /* 연속으로 오류를 낸 횟수. 정상 반환이 나오면 0 으로 돌아감 */
    int disabled;                 /* 1 이면 디스패처가 이 탐지기를 건너뜀 */
};

#endif /* DETECTOR_H */
